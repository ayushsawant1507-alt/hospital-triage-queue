"""
triage.models
=============
Domain model for the Hospital / Emergency Triage Queue.

Contains
--------
Severity  : IntEnum ranking clinical urgency (1 = most critical, 5 = least).
Patient   : Immutable-ish dataclass representing a single ER patient.

Ordering contract
-----------------
``Patient.__lt__`` uses the composite key ``(severity, arrival_seq)`` only.
Because ``arrival_seq`` is a globally unique, monotone counter assigned at
admission time, no two distinct Patient objects can share the same key.
This makes the ordering **total** — every pair is strictly comparable with
no ties possible.

Why total order makes stability irrelevant for heap sort
--------------------------------------------------------
Stability matters only when two elements compare *equal*: a stable sort
preserves their original relative order while an unstable one may not.
Since ``key = (severity, arrival_seq)`` admits no ties, heap sort (which is
NOT stable) must produce the identical unique sequence as any stable sort.
The FIFO guarantee on same-severity patients is encoded directly in the
key (earlier ``arrival_seq`` => smaller key => dequeued first) rather than
being left to the algorithm's stability property.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import IntEnum
from typing import Tuple


# ---------------------------------------------------------------------------
# Severity
# ---------------------------------------------------------------------------

class Severity(IntEnum):
    """
    Clinical urgency levels for the Emergency Room triage system.

    Lower integer value = higher clinical priority.

    Values
    ------
    CRITICAL   (1) : Immediately life-threatening; resuscitation required.
    EMERGENT   (2) : High risk of deterioration; seen within 15 minutes.
    URGENT     (3) : Stable but needs care within 30 minutes.
    LESS_URGENT(4) : Could wait up to 60 minutes.
    NON_URGENT (5) : Non-urgent; same-day or next-day care acceptable.
    """

    CRITICAL    = 1
    EMERGENT    = 2
    URGENT      = 3
    LESS_URGENT = 4
    NON_URGENT  = 5


# ---------------------------------------------------------------------------
# Patient
# ---------------------------------------------------------------------------

@dataclass
class Patient:
    """
    Represents a single patient in the ER triage system.

    Attributes
    ----------
    id          : Unique patient identifier (hospital record number).
    name        : Patient's full name.
    severity    : Clinical urgency level (Severity enum).
    arrival_seq : Globally unique, monotone admission counter.
                  Assigned once at triage; never modified.

    Ordering
    --------
    Defined solely by the ``key`` property ``(severity, arrival_seq)``.

    ``__eq__`` is the dataclass default (compares all four fields), which
    correctly models true object identity.  ``__lt__`` (and companions) use
    only the key so that heap-based structures see a total, deterministic
    order without relying on algorithm stability.

    Thread safety
    -------------
    Not thread-safe.  ``arrival_seq`` must be assigned by a single
    monotone counter in the caller.
    """

    id:          int
    name:        str
    severity:    Severity
    arrival_seq: int

    # ------------------------------------------------------------------
    # Comparison key
    # ------------------------------------------------------------------

    @property
    def key(self) -> Tuple[int, int]:
        """
        Composite sort key: ``(severity, arrival_seq)``.

        * Lower severity integer  => higher clinical priority.
        * For equal severity, lower arrival_seq => arrived earlier =>
          served first (FIFO tie-breaking).

        Returns
        -------
        Tuple[int, int]
            ``(int(self.severity), self.arrival_seq)``
        """
        return (int(self.severity), self.arrival_seq)

    # ------------------------------------------------------------------
    # Rich comparisons  (all delegate to key)
    # ------------------------------------------------------------------

    def __lt__(self, other: "Patient") -> bool:
        """
        Return ``True`` if *self* has higher clinical priority than *other*.

        Time  : O(1)
        Space : O(1)
        """
        return self.key < other.key

    def __le__(self, other: "Patient") -> bool:
        return self.key <= other.key

    def __gt__(self, other: "Patient") -> bool:
        return self.key > other.key

    def __ge__(self, other: "Patient") -> bool:
        return self.key >= other.key

    # Note: __eq__ is generated by @dataclass (compares all four fields).
    # __hash__ is set to None by @dataclass(eq=True) -- Patients are not
    # hashable by default; use patient.id as the dict/set key instead.

    def __repr__(self) -> str:
        return (
            f"Patient(id={self.id}, name={self.name!r}, "
            f"severity={self.severity.name}, arrival_seq={self.arrival_seq})"
        )
